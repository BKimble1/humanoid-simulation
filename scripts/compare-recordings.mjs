#!/usr/bin/env node
// Compares the telemetry of two sets of recordings (scripts/probe.mjs --video writes
// <scenario>.json; docs/recordings/<set>/<scenario>.telemetry.json keeps them) and prints a
// Markdown table: the worst frame of each measurement, per scenario, before and after.
//
//   node scripts/compare-recordings.mjs docs/recordings/v1 docs/recordings/v2 > docs/recordings/COMPARISON.md
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const [a, b] = process.argv.slice(2);
if (!a || !b) {
  console.error('usage: node scripts/compare-recordings.mjs <before dir> <after dir>');
  process.exit(2);
}
const load = (dir, name) => {
  const f = join(dir, `${name}.telemetry.json`);
  return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null;
};
const names = readdirSync(a)
  .filter((f) => f.endsWith('.telemetry.json'))
  .map((f) => f.replace('.telemetry.json', ''))
  .filter((n) => existsSync(join(b, `${n}.telemetry.json`)));

const MEASURES = [
  ['jv', 'joint speed, rad/s', 1],
  ['ja', 'joint acceleration, rad/s²', 0],
  ['hv', 'hand pose rate, 1/s', 2],
  ['pv', 'pelvis speed, m/s (not walking)', 2],
  ['ca', 'camera acceleration, m/s²', 1],
  ['cc', 'camera clearance (lowest), m', 2],
  ['slip', 'planted sole slip, m/s', 3],
  ['ov', 'object speed, m/s', 2],
];
const value = (s, k) => (k === 'slip' ? Math.max(s.slipL, s.slipR) : s[k]);
function worst(samples, k) {
  if (!samples.length) return NaN;
  if (k === 'cc') return Math.min(...samples.map((s) => s.cc));
  const pool = k === 'pv' ? samples.filter((s) => s.source !== 'walk') : samples;
  return pool.length ? Math.max(...pool.map((s) => value(s, k))) : NaN;
}

const out = [];
out.push(`# Recordings: ${a} → ${b}`, '');
out.push('Worst frame of each measurement in each recorded scenario (developer telemetry, every frame, frame-stepped at 30 frames/s). Generated by `scripts/compare-recordings.mjs`.', '');
out.push("Joint speed and acceleration include walking's own strides where a scenario walks (a knee in swing reaches 7 rad/s): those maxima are the gait, the same in both. Pelvis speed leaves walking out. Camera acceleration in V2 is higher in places because V2's moves are shorter (mostly 0.8–1.8 s); its tests hold it to 15 m/s².", '');
for (const n of names) {
  const A = load(a, n);
  const B = load(b, n);
  out.push(`## ${n}`, '');
  out.push(`| measurement | ${a.split('/').pop()} | ${b.split('/').pop()} |`, '|---|---|---|');
  for (const [k, label, dp] of MEASURES) {
    const x = worst(A.samples, k);
    const y = worst(B.samples, k);
    if (!Number.isFinite(x) && !Number.isFinite(y)) continue;
    out.push(`| ${label} | ${Number.isFinite(x) ? x.toFixed(dp) : '—'} | ${Number.isFinite(y) ? y.toFixed(dp) : '—'} |`);
  }
  // pause: how many paused frames still showed motion
  const moving = (S) => {
    const p = S.samples.filter((s) => s.paused);
    return p.length ? `${p.filter((s) => s.jv > 1e-4 || s.pv > 1e-5 || s.cv > 1e-5 || s.hv > 1e-4).length} of ${p.length} paused frames moved` : null;
  };
  const ma = moving(A);
  const mb = moving(B);
  if (ma || mb) out.push(`| while paused | ${ma ?? '—'} | ${mb ?? '—'} |`);
  // exploded assemblies: how each newly shown one appears
  const appear = (S) => {
    let prev = S.samples[0]?.assemblies ?? '';
    const r = [];
    for (const s of S.samples) {
      if (s.assemblies && s.assemblies !== prev) r.push(`${s.assemblies} at explode ${s.explode.toFixed(2)}`);
      prev = s.assemblies;
    }
    return r.length ? r.join('; ') : null;
  };
  const pa = appear(A);
  const pb = appear(B);
  if (pa || pb) out.push(`| a newly shown actuator appears | ${pa ?? '—'} | ${pb ?? '—'} |`);
  out.push('');
}
console.log(out.join('\n'));
